"""Упрощённый агент: отвечает по правилам, без RAG и внешних API"""

def process_message(client_id, user_message, state, history, summary):
    msg = user_message.lower()

    # FAQ
    if "виза" in msg and "турция" in msg:
        reply = "Нет, для россиян виза в Турцию не нужна."
    elif "что входит" in msg or "входит в стоимость" in msg:
        reply = "В стоимость тура входят: перелёт, проживание, трансфер, страховка, питание (если указано в туре)."
    elif "предоплата" in msg:
        reply = "Да, предоплата 30%, остаток за неделю до выезда."

    # Квалификация
    elif "турцию" in msg or "турция" in msg:
        reply = "Отлично! На какие даты планируете поездку и сколько дней хотите отдохнуть?"
    elif any(x in msg for x in ["взрослый", "детей", "ребёнок"]):
        reply = "Какой примерный бюджет на тур (в рублях)? Это поможет сразу отсеять неподходящие варианты."
    elif any(x in msg for x in ["июль", "август", "июнь", "сентябрь"]):
        reply = "Сколько едет взрослых и сколько детей (если есть)? Возраст детей важен для подбора отеля."
    elif any(x in msg for x in ["тысяч", "бюджет", "рубл"]):
        reply = "Принято! Есть ли особые пожелания — первая линия, тихий район, отель с аквапарком?"

    # Возражения
    elif "дорого" in msg or "цена" in msg:
        reply = "Понимаю, цена важна. В стоимость уже включены перелёт, отель, трансфер и страховка. Давайте подберу 3 варианта в разных ценовых сегментах."
    elif "подумаю" in msg:
        reply = "Конечно, решение стоит обдумать. Пока вы думаете, цены могут измениться. Давайте я пришлю 3 варианта — сможете вернуться к ним позже."
    elif "у другого дешевле" in msg or "у других дешевле" in msg:
        reply = "Часто у конкурентов цена ниже, потому что трансфер или страховка не включены. У нас цена «всё включено» — сразу видно, что вы получаете."

    # Эскалация
    elif any(x in msg for x in ["бронировать", "забронировать", "готов оплатить", "хочу оплатить"]):
        reply = "Ваш запрос передан менеджеру. Алексей свяжется с вами в течение 15 минут."
        return {"reply": reply, "emotion": "neutral", "escalate": True,
                "new_state": "escalated", "raw_reply": reply}

    # По умолчанию
    else:
        reply = "Расскажите чуть подробнее: куда хотите поехать, на какие даты и какой бюджет? Так я смогу подобрать лучшие варианты."

    # Простой переход состояний
    new_state = state
    if state == "new":
        new_state = "greeting"
    elif state == "greeting":
        new_state = "qualifying"

    return {"reply": reply, "emotion": "neutral", "escalate": False,
            "new_state": new_state, "raw_reply": reply}
