"""Эмпатия: распознавание эмоций клиента и адаптация тона"""
import re


EMOTION_PATTERNS = {
    "frustration": [r"дорого", r"обман", r"уже третий раз", r"устал", r"бесит",
                    r"разочарован", r"ужас", r"ненавижу", r"отвратител"],
    "joy": [r"ура", r"супер", r"в восторге", r"отлично", r"здорово",
            r"спасибо", r"благодар", r"прекрасно", r"класс"],
    "doubt": [r"подумаю", r"не уверен", r"сомнева", r"может быть",
              r"наверное", r"пожалуй", r"сложно сказать"],
    "urgency": [r"срочно", r"горит", r"завтра нужно", r"крайний срок",
                r"очень надо", r"быстрее", r"некогда"],
    "fear": [r"боюсь", r"вдруг", r"что если", r"опасаюс", r"тревож",
             r"пережива", r"страшно"],
    "distrust": [r"не верю", r"у других лучше", r"обманули", r"недовер",
                 r"вы уверены", r"точно ли"],
}


def detect_emotion(text: str) -> str:
    text_lower = text.lower()
    for emotion, patterns in EMOTION_PATTERNS.items():
        for p in patterns:
            if re.search(p, text_lower):
                return emotion
    return "neutral"


EMPATHY_INSTRUCTIONS = {
    "frustration": ("Клиент раздражён или расстроен. Признай его чувства без обесценивания. "
                    "Не преуменьшай проблему. Мягкий тон, без роботности. Покажи, что ты на его стороне."),
    "joy": ("Клиент радостен. Поддержи его энтузиазм, раздели радость. "
            "Тон тёплый, дружелюбный, но не чрезмерный."),
    "doubt": ("Клиент сомневается. Не дави, дай ему время. "
              "Подкинь полезную информацию, которая поможет решиться. Без агрессивных продаж."),
    "urgency": ("Клиенту срочно. Коротко, по делу, без лишних вопросов. "
                "Быстро дай решение или переведи на человека."),
    "fear": ("Клиент боится или тревожится. Успокой, приведи гарантии и кейсы. "
             "Не преуменьшай его страхи, а адресуй их конкретикой."),
    "distrust": ("Клиент потерял доверие. Не оправдывайся — дай факты и цифры. "
                 "Без шаблонных фраз. Честно и прямо."),
    "neutral": "",
}


def get_empathy_instruction(emotion: str) -> str:
    return EMPATHY_INSTRUCTIONS.get(emotion, "")
